export function flyoverLift(s) {
  let lift = 0;
  for (const start of [260, 790]) {
    const t = (s - start) / 180;
    if (t > 0 && t < 1) lift += 10 * Math.sin(Math.PI * t) ** 2;
  }
  return lift;
}
